GLYPH_W, GLYPH_H = 5, 7
_MASKS = {k: np.array([[c == "#" for c in row] for row in v], dtype=bool) for k, v in _GLYPHS.items()}


def glyph(ch):
    if ch in _MASKS:
        return _MASKS[ch]
    up = ch.upper()
    return _MASKS.get(up, _MASKS["?"])


def text_width(s, scale=1, spacing=1):
    if not s:
        return 0
    return (len(s) * (GLYPH_W + spacing) - spacing) * scale


def text_mask(s, scale=1, spacing=1):
    """Boolean mask for a single line of text at an integer scale."""
    w = len(s) * (GLYPH_W + spacing) - spacing
    m = np.zeros((GLYPH_H, max(w, 1)), dtype=bool)
    for i, ch in enumerate(s):
        x = i * (GLYPH_W + spacing)
        m[:, x:x + GLYPH_W] |= glyph(ch)
    if scale != 1:
        m = np.repeat(np.repeat(m, scale, axis=0), scale, axis=1)
    return m


def dilate(m, r=1):
    """8-neighbourhood dilation of a bool mask, grown by r pixels on each side."""
    h, w = m.shape
    out = np.zeros((h + 2 * r, w + 2 * r), dtype=bool)
    for dy in range(-r, r + 1):
        for dx in range(-r, r + 1):
            out[r + dy:r + dy + h, r + dx:r + dx + w] |= m
    return out
